#!/usr/bin/env python3
"""Porter feedback check: list new, unprocessed feedback on the porter's PRs and watched core PRs.

Usage: python3 feedback/check.py [--save]
  Reads feedback/checkpoint.json, asks GitHub (gh api) for every open PR whose head branch starts
  with port/, proposal/ or docs/porter, plus the PR numbers in checkpoint["watch"], and prints each
  comment, review or review comment newer than the checkpoint that is not written by a Claude
  session (Claude's own posts end with the "Generated by [Claude Code]" footer). It also prints
  PRs whose head commit changed. With --save it writes the new checkpoint (call it only after the
  printed items are dealt with). Exit 0 always; "NOTHING NEW" when there is nothing to do.
"""
import json, subprocess, sys, os
REPO = 'lglouis3-create/exam-drill-kit'
HERE = os.path.dirname(os.path.abspath(__file__))
CP = os.path.join(HERE, 'checkpoint.json')
FOOTER = 'Generated by [Claude Code]'
def api(path):
    out = subprocess.run(['gh', 'api', '--paginate', path], capture_output=True, text=True)
    if out.returncode: raise SystemExit('gh api failed: ' + path + ': ' + out.stderr.strip()[:300])
    txt = out.stdout.strip().replace('][', ',')
    return json.loads(txt or '[]')
cp = json.load(open(CP)) if os.path.exists(CP) else {'prs': {}, 'watch': []}
prs = {p['number']: p for p in api(f'repos/{REPO}/pulls?state=open&per_page=100')
       if p['head']['ref'].startswith(('port/', 'proposal/', 'docs/porter'))}
for n in cp.get('watch', []):
    if n not in prs:
        p = json.loads(subprocess.run(['gh', 'api', f'repos/{REPO}/pulls/{n}'], capture_output=True, text=True).stdout or '{}')
        if p.get('state') == 'open': prs[n] = p
new, state = [], {}
for n, p in sorted(prs.items()):
    old = cp['prs'].get(str(n), {})
    items = []
    for kind, path in (('comment', f'repos/{REPO}/issues/{n}/comments?per_page=100'),
                       ('review', f'repos/{REPO}/pulls/{n}/reviews?per_page=100'),
                       ('review-comment', f'repos/{REPO}/pulls/{n}/comments?per_page=100')):
        for c in api(path):
            items.append((kind, c['id'], c.get('created_at') or c.get('submitted_at') or '', c.get('body') or '', c.get('commit_id') or ''))
    seen = set(old.get('ids', []))
    for kind, i, at, body, commit in items:
        if i in seen or FOOTER in body: continue
        new.append(f'#{n} {kind} {i} {at} {("on " + commit[:7]) if commit else ""}\n    ' + body.strip().replace('\n', '\n    ')[:1500])
    head = p['head']['sha']
    if old.get('head') and old['head'] != head:
        new.append(f'#{n} head changed {old["head"][:7]} -> {head[:7]}')
    state[str(n)] = {'head': head, 'ids': sorted(i for _, i, *_ in items)}
print('\n'.join(new) if new else 'NOTHING NEW')
if '--save' in sys.argv:
    cp['prs'] = state
    json.dump(cp, open(CP, 'w'), indent=1, sort_keys=True); print('checkpoint saved')
